import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import { localStatus, localSql, localAdmin } from './local-supabase.mjs';
import { createFixture } from '../tests/integration/local-fixtures.mjs';
import { capturedLink } from '../tests/integration/local-mail.mjs';

const status = localStatus();
const client = () => createClient(status.API_URL, status.PUBLISHABLE_KEY ?? status.ANON_KEY, { db: { schema: 'api' }, auth: { persistSession: false, autoRefreshToken: false } });
const fixture = await createFixture();
const a = client(); const b = client(); const anon = client();
let checks = 0;
const extraUsers = [];
function check(condition, message) { assert.ok(condition, message); checks++; }
try {
  const admin = localAdmin();
  const email = `mail-${randomUUID()}@example.test`;
  const invitation = await admin.auth.admin.inviteUserByEmail(email, { redirectTo: 'http://127.0.0.1:5173/auth/confirm' });
  check(!invitation.error && Boolean(invitation.data.user), 'operator invitation is captured locally');
  extraUsers.push(invitation.data.user.id);
  const mailClient = client();
  const inviteHash = await capturedLink(email, 'invite');
  check(!(await mailClient.auth.verifyOtp({ token_hash: inviteHash, type: 'invite' })).error, 'actual invitation email template works');
  check((await mailClient.from('households').select()).data.length === 0, 'invited identity without membership cannot see a household');
  await mailClient.auth.signOut();
  // Respect the configured per-recipient minimum delivery interval.
  await new Promise((resolve) => setTimeout(resolve, 1100));
  const emailSignIn = await mailClient.auth.signInWithOtp({ email, options: { shouldCreateUser: false, emailRedirectTo: 'http://127.0.0.1:5173/auth/confirm' } });
  check(!emailSignIn.error, `existing invited user can request email sign-in (${emailSignIn.error?.code ?? 'ok'})`);
  const magicHash = await capturedLink(email, 'email');
  check(!(await mailClient.auth.verifyOtp({ token_hash: magicHash, type: 'email' })).error, 'actual magic-link template works');
  await mailClient.auth.signOut();
  const expiring = await admin.auth.admin.generateLink({ type: 'invite', email: `expired-${randomUUID()}@example.test` });
  check(!expiring.error && Boolean(expiring.data.user), 'expiry fixture created');
  extraUsers.push(expiring.data.user.id);
  localSql(`update auth.users set confirmation_sent_at=now()-interval '1 day' where id='${expiring.data.user.id}';`);
  check(Boolean((await mailClient.auth.verifyOtp({ token_hash: expiring.data.properties.hashed_token, type: 'invite' })).error), 'expired invitation rejected by Auth');
  check(Boolean((await anon.auth.signUp({ email: `uninvited-${randomUUID()}@example.test`, password: randomUUID() })).error), 'public signup must be disabled');
  check(Boolean((await anon.auth.signInWithOtp({ email: `uninvited-${randomUUID()}@example.test`, options: { shouldCreateUser: false } })).error), 'unknown OTP request must not create user');
  check(Boolean((await anon.from('households').select()).error), 'anonymous API read denied');
  check(Boolean((await a.auth.verifyOtp({ token_hash: '0'.repeat(64), type: 'invite' })).error), 'invalid invite rejected');
  for (const [index, c] of [a,b].entries()) check(!(await c.auth.verifyOtp({ token_hash: fixture.users[index].hash, type: 'invite' })).error, 'real invitation accepted');
  check(Boolean((await anon.auth.verifyOtp({ token_hash: fixture.users[0].hash, type: 'invite' })).error), 'reused invite rejected');
  const before = await a.auth.getSession();
  const token = before.data.session.access_token;
  const aRead = await a.from('households').select();
  const bRead = await b.from('households').select();
  check(!aRead.error && aRead.data.length === 1 && aRead.data[0].id === fixture.households[0], 'A REST isolation');
  check(!bRead.error && bRead.data.length === 1 && bRead.data[0].id === fixture.households[1], 'B REST isolation');
  const escaped = await a.schema('finance').from('households').select();
  check(Boolean(escaped.error), 'finance schema not exposed');
  check(Boolean((await a.from('household_members').update({ status: 'ACTIVE' }).eq('user_id',fixture.users[1].id)).error), 'unauthorized membership command rejected');
  const renamed = await a.rpc('rename_profile', { display_name: 'Updated synthetic' });
  check(!renamed.error && renamed.data.ok, 'authenticated safe command');
  check((await a.rpc('rename_profile',{display_name:''})).data.error.code === 'INVALID_INPUT','safe validation response');
  check(!(await a.auth.refreshSession()).error, 'session refresh succeeds');
  localSql(`update finance.household_members set status='REVOKED' where user_id='${fixture.users[0].id}';`);
  check((await a.from('households').select()).data.length === 0, 'removed membership applies to existing session');
  localSql(`update finance.household_members set status='ACTIVE' where user_id='${fixture.users[0].id}';`);
  check((await a.from('households').select()).data.length === 1, 'membership restored before logout replay test');
  check(!(await a.auth.signOut()).error, 'server logout succeeds');
  const replay = await fetch(`${status.API_URL}/rest/v1/households?select=*`, { headers: { apikey: status.PUBLISHABLE_KEY ?? status.ANON_KEY, Authorization: `Bearer ${token}`, 'Accept-Profile': 'api' } });
  check(replay.ok && (await replay.json()).length === 0, 'logged-out JWT cannot read households');
  check(Boolean((await a.auth.refreshSession()).error), 'logged-out session cannot refresh');
  const bSession = (await b.auth.getSession()).data.session;
  const memberBefore = (await b.from('household_members').select()).data[0];
  check(!(await admin.auth.admin.deleteUser(fixture.users[1].id)).error, 'real Auth admin deletion succeeds');
  check(localSql(`select count(*) from finance.household_members where id='${memberBefore.id}' and user_id is null and status='REVOKED' and display_name='Synthetic B';`) === '1', 'Auth deletion retains durable member and display attribution');
  const deletedReplay = await fetch(`${status.API_URL}/rest/v1/households?select=*`, { headers: { apikey: status.PUBLISHABLE_KEY ?? status.ANON_KEY, Authorization: `Bearer ${bSession.access_token}`, 'Accept-Profile': 'api' } });
  check(deletedReplay.ok && (await deletedReplay.json()).length === 0, 'deleted Auth identity cannot replay its still-signed JWT');
  const reinvited = await admin.auth.admin.generateLink({ type: 'invite', email: fixture.users[1].email });
  check(!reinvited.error && reinvited.data.user.id !== fixture.users[1].id, 'same email invitation creates a distinct login identity');
  extraUsers.push(reinvited.data.user.id);
  check(!(await anon.auth.verifyOtp({ token_hash: reinvited.data.properties.hashed_token, type: 'invite' })).error, 'replacement login can authenticate');
  check((await anon.from('households').select()).data.length === 0, 'same-email replacement does not inherit membership');
  check(Boolean((await anon.from('household_members').update({ user_id: reinvited.data.user.id, status: 'ACTIVE' }).eq('id',memberBefore.id)).error), 'replacement login cannot claim retained membership through API');
  await anon.auth.signOut();
  console.log(`Auth/API integration: ${checks} assertions passed against local GoTrue and PostgREST.`);
} finally { await a.auth.signOut(); await b.auth.signOut(); await fixture.cleanup(); for (const id of extraUsers) await localAdmin().auth.admin.deleteUser(id); }
