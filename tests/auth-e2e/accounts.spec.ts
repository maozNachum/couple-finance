import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { createFixture } from '../integration/local-fixtures.mjs';
import { localSql, uuid } from '../../scripts/local-supabase.mjs';

test('manual account, dated FX, correction, archival and revoked access', async ({ page }, testInfo) => {
  const fixture = await createFixture();
  try {
    const user = fixture.users[0]; if (!user) throw new Error('Missing fixture');
    await page.goto(`/auth/confirm#token_hash=${user.hash}&type=invite`);
    await page.getByRole('button', { name: 'אישור כניסה' }).click();
    await expect(page.getByRole('heading', { name: 'Synthetic household A' })).toBeVisible();
    await page.getByRole('link', { name: 'חשבונות', exact: true }).click();
    await expect(page.getByText('אין עדיין חשבונות. אפשר ליצור את החשבון הראשון.')).toBeVisible();
    const form = page.getByRole('form', { name: 'חשבון חדש' });
    await form.getByLabel('שם החשבון').fill('Synthetic loan');
    await form.getByLabel('סוג חשבון').selectOption('LOAN');
    await form.getByRole('combobox', { name: 'שיוך', exact: true }).selectOption({ label: 'Synthetic A' });
    await form.getByLabel('מטבע החשבון').selectOption('USD');
    await form.getByRole('button', { name: 'יצירת חשבון' }).click();
    await expect(page.getByRole('heading', { name: 'Synthetic loan', exact: true })).toBeVisible();
    await expect(page.getByText('אין תצפית שווי בתאריך זה או לפניו.')).toBeVisible();
    const observation = page.getByRole('form', { name: 'תצפית שווי' });
    await observation.getByRole('textbox', { name: 'תאריך התצפית', exact: true }).fill('2026-10-01');
    await observation.getByLabel('סכום ב־USD').fill('-100');
    await observation.getByLabel('כיסוי השווי').selectOption('PARTIAL');
    await observation.getByLabel('שער ידני לתאריך התצפית:', { exact: false }).fill('3.72');
    await observation.getByRole('button', { name: 'שמירת תצפית' }).click();
    await expect(page.getByText('שווי במטבע היעד:')).toContainText('-372.00 ILS');
    await expect(page.getByText('שווי חלקי — חסרים רכיבים')).toBeVisible();
    await page.getByLabel('שווי נכון לתאריך').fill('2026-09-30');
    await expect(page.getByText('אין תצפית שווי בתאריך זה או לפניו.')).toBeVisible();
    await page.getByLabel('שווי נכון לתאריך').fill('2026-10-05');
    await page.getByText('היסטוריית תצפיות (1)', { exact: true }).click();
    await page.getByRole('button', { name: 'תיקון תצפית 2026-10-01' }).click();
    await observation.getByLabel('סכום ב־USD').fill('-90');
    await observation.getByLabel('סיבת התיקון').fill('Synthetic correction');
    await observation.getByRole('button', { name: 'שמירת תצפית' }).click();
    await expect(page.getByText('חסר שער חליפין לתאריך התצפית.')).toBeVisible();
    await page.getByText('היסטוריית תצפיות (2)', { exact: true }).click();
    await expect(page.getByText('הוחלף בתיקון', { exact: false })).toBeVisible();
    await expect(page.getByText('תצפית אחרונה ל־2026-10-01:')).toContainText('-90.00 USD');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: `.artifacts/task4-${testInfo.project.name}.png`, fullPage: true });
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await page.getByRole('button', { name: 'העברה לארכיון' }).click();
    await expect(page.getByText('בארכיון', { exact: false })).toBeVisible();
    await expect(page.getByRole('form', { name: 'תצפית שווי' })).toHaveCount(0);
    await form.getByLabel('שם החשבון').fill('Synthetic cash');
    await form.getByLabel('סוג חשבון').selectOption('CASH');
    await form.getByRole('button', { name: 'יצירת חשבון' }).click();
    await expect(page.getByText('יתרה אינה זמינה: ספר התנועות יתווסף בשלב הבא.')).toBeVisible();
    localSql(`update finance.household_members set status='REVOKED' where household_id='${uuid(fixture.households[0]!)}' and user_id='${uuid(user.id)}';`);
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await expect(page.getByText('אין כרגע גישה לבית.')).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Synthetic loan' })).toHaveCount(0);
    expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 });
  } finally { await fixture.cleanup(); }
});
